# SVD, PCA'nın daha genel bir biçimidir ve gürültü azaltma, veri sıkıştırma, öneri sistemleri (matris tamamlama) gibi alanlarda kullanılır.
# California Housing verisini SVD ile sıkıştırıp, kaç bileşenle verinin çoğu bilgisinin korunduğunu görelim.

X_house_scaled = StandardScaler().fit_transform(X_house)
U, S_values, Vt = np.linalg.svd(X_house_scaled, full_matrices=False)

explained_var = (S_values**2) / np.sum(S_values**2)
cumulative_var = np.cumsum(explained_var)

fig, ax = plt.subplots(figsize=(8,5))
ax.bar(range(1, len(S_values)+1), explained_var*100, alpha=0.6, color='#3498db', label='Bileşen başına')
ax.plot(range(1, len(S_values)+1), cumulative_var*100, color='#e74c3c', marker='o', label='Kümülatif')
ax.axhline(95, color='gray', ls='--', lw=1, label='%95 eşiği')
ax.set_xlabel('Tekil Değer (Bileşen) Sayısı')
ax.set_ylabel('Açıklanan Varyans (%)')
ax.set_title('SVD: California Housing (8 özellik) İçin\nKaç Bileşen Yeterli?')
ax.legend()
plt.tight_layout()
plt.show()

n_95 = np.argmax(cumulative_var >= 0.95) + 1
print(f"Varyansın %95'ini korumak için yeterli bileşen sayısı: {n_95} / {X_house.shape[1]}")

