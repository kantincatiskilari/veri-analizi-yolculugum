# 2 - Nokta Çarpımı (Dot Product): Benzerlik Ölçüsü

# İki veri noktası (örn. iki çiçek) ne kadar "benzer yönde" ise o kadar benzerdir. (Kosinus benzerligi)

def cosine_similarity(v, w):
  return np.dot(v, w) / (np.linalg.norm(v) * np.linalg.norm(w))

# Her sınıftan bir örnek alalım (4 boyutlu tam vektör)
