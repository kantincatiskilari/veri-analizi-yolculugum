# 8 - Özdeğerler ve Özvektörler

# Bir özvektör, bir dönüşüm sırasında yönünü değiştirmeyen, sadece özdeğeri kadar ölçeklenen özel bir vektördür: Av = λv.

# Veri biliminde PCA (Temel Bileşen Analizi), verinin kovaryans matrisinin özvektörlerini bulur.
# En büyük özdeğere sahip özvektör, verinin en çok yayıldığı yönü gösterir — yani "en bilgilendirici" yönü.

X4 = X_iris  # tüm 4 özellik
X4_centered = X4 - X4.mean(axis=0)

# Kovaryans matrisi
cov_matrix = np.cov(X4_centered.T)
print("Kovaryans matrisi (4x4):\n", cov_matrix)

# Özdeğer/özvektör ayrışımı
eigvals, eigvecs = np.linalg.eigh(cov_matrix)
# eigh küçükten büyüğe sıralar -> büyükten küçüğe çevirelim
order = np.argsort(eigvals)[::-1]
eigvals, eigvecs = eigvals[order], eigvecs[:, order]

print("\nÖzdeğerler (büyükten küçüğe):", eigvals)
print("\nAçıklanan varyans oranı:", eigvals / eigvals.sum())

fig, ax = plt.subplots(figsize=(7,5))
ax.bar(range(1,5), eigvals/eigvals.sum()*100, color='#3498db')
for i,v in enumerate(eigvals/eigvals.sum()*100):
    ax.text(i+1, v+1, f"{v:.1f}%", ha='center')
ax.set_xlabel('Özvektör (Temel Bileşen)')
ax.set_ylabel('Açıklanan Varyans (%)')
ax.set_title('Her Özdeğer, İlgili Özvektör Yönündeki\n"Bilgi Miktarını" Gösterir')
ax.set_xticks(range(1,5))
plt.tight_layout()
plt.show()

"""Gözlem: İlk özdeğer tek başına verinin varyansının büyük kısmını açıklıyor. Bu, 4 boyutlu Iris verisinin aslında "gerçekte" çok daha az boyutlu bir yapıda yaşadığı anlamına gelir"""

# 9 - Taban Değişimi: PCA ile Boyut İndirgeme

# Bir "taban" (basis), uzayı tanımlamak için seçtiğimiz eksen takımıdır.
