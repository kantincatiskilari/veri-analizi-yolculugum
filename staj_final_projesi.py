# 3 - Lineer Dönüşümler: Matrisler Uzayı Nasıl Değiştirir?

# Bir matris, uzaydaki ızgarayı (grid) nasıl deforme ettiğini gösteren bir dönüşümdür. Sütunları, temel vektörlerin (î, ĵ) nereye gittiğini söyler.

# StandardScaler, PCA, hatta bir sinir ağının her katmanı, veriye uygulanan birer lineer dönüşümdür.

def plot_grid_transform(ax, M, title, xlim=(-3,3), ylim=(-3,3)):
    """Bir matrisin 2D ızgarayı nasıl dönüştürdüğünü çizer."""
    grid_range = np.arange(-4, 5, 1)
    for gx in grid_range:
        pts = np.array([[gx, y] for y in np.linspace(-4, 4, 50)])
        tpts = pts @ M.T
        ax.plot(tpts[:,0], tpts[:,1], color='lightgray', lw=0.7, zorder=1)
    for gy in grid_range:
        pts = np.array([[x, gy] for x in np.linspace(-4, 4, 50)])
        tpts = pts @ M.T
        ax.plot(tpts[:,0], tpts[:,1], color='lightgray', lw=0.7, zorder=1)

    # temel vektörler î ve ĵ'nin gittiği yer
    i_hat = M @ np.array([1,0])
    j_hat = M @ np.array([0,1])
    ax.annotate('', xy=i_hat, xytext=(0,0), arrowprops=dict(arrowstyle='->', color='red', lw=2.5))
    ax.annotate('', xy=j_hat, xytext=(0,0), arrowprops=dict(arrowstyle='->', color='blue', lw=2.5))
    ax.text(*i_hat, "  î'", color='red', fontsize=12, fontweight='bold')
    ax.text(*j_hat, "  ĵ'", color='blue', fontsize=12, fontweight='bold')

    ax.set_xlim(xlim); ax.set_ylim(ylim)
    ax.set_aspect('equal')
    ax.set_title(title)
    ax.axhline(0, color='k', lw=0.5); ax.axvline(0, color='k', lw=0.5)

# Örnek dönüşüm: ölçekleme + kesme (shear)
M_scale = np.array([[2, 0],
                     [0, 0.5]])
M_shear = np.array([[1, 0.8],
                     [0, 1]])

fig, axes = plt.subplots(1, 2, figsize=(13, 6))
plot_grid_transform(axes[0], M_scale, "Ölçekleme Matrisi\nM = [[2,0],[0,0.5]]")
plot_grid_transform(axes[1], M_shear, "Kesme (Shear) Matrisi\nM = [[1,0.8],[0,1]]")
plt.tight_layout()
plt.show()

