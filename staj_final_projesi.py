print(f"{'':15}", *[f"{l:12}" for l in labels])
for i, vi in enumerate(samples):
    row = [cosine_similarity(vi, vj) for vj in samples]
    print(f"{labels[i]:15}", *[f"{r:12.3f}" for r in row])

# Görselleştirme: benzerlik matrisini ısı haritası olarak göster
sim_matrix = np.array([[cosine_similarity(vi, vj) for vj in samples] for vi in samples])
