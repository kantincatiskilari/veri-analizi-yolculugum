"""StandardScaler lineer (doğrusal) bir dönüşümdür. Sağdaki ve soldaki noktaların birbiriyle olan göreceli konumları, yönleri ve açıları birebir aynıdır. Standartlaştırma verinin şeklini, küme içi kümelenmeyi veya sınıf ayrılabilirliğini bozmaz ya da geliştirmez.

Gözlem: Noktaların göreli konumu (kümelenme yapısı) korunuyor, ama eksenler yeniden ölçekleniyor. Uzay deforme oluyor ama orijin sabit kalıyor ve doğrular doğru kalıyor. Bu, "lineer" dönüşümün tanımıdır.

Bu grafik standartlaştırmanın türler arasındaki mesafeyi/oranı değiştirmediğini, sadece tüm öznitelikleri ortak bir ölçekte sıfır noktasına merkeze aldığını açıkça kanıtlıyor.

Neden Standart Scaling yaptık?

Görsel ve Geometrik Kolaylık: Yüklediğin sağdaki grafikte fark ettiğin gibi, $0$ çizgisi tam merkezdedir. Değerin negatif mi pozitif mi olduğuna bakarak verinin ortalamanın altında mı üstünde mi kaldığını tek bakışta anlarsın.

PCA (Temel Bileşenler Analizi) ve Kovaryans Hesapları: PCA gibi boyut indirgeme yöntemleri, verinin eksen etrafındaki varyansını hesaplar. Veri sıfıra merkezlenmediğinde kovaryans matrisi ve özvektör (eigenvector) hesaplamaları yanlış veya kaymış sonuçlar verir.

Kosinüs Benzerliği: Kosinüs benzerliği orijinden çıkan vektörler arasındaki açıya bakar. Eğer veri merkezlenmezse (tüm değerler pozitif kalırsa), tüm vektörler $1.$ bölgede sıkışır ve aralarındaki açı yapay olarak birbirine çok yakın çıkar. Merkezleme yapıldığında gerçek yönsel farklar ortaya çıkar.
"""

# 5 - Matris Çarpımı

# AB çarpımı, "önce B uygula, sonra A uygula" demektir — iki ardışık dönüşümün tek bir dönüşümde birleştirilmesidir.

theta = np.radians(30)
R = np.array([[np.cos(theta), -np.sin(theta)],
              [np.sin(theta),  np.cos(theta)]])  # 30 derece döndürme
S = np.array([[1.5, 0],
              [0, 0.7]])                          # eksenel ölçekleme

combined = R @ S   # önce S (ölçekle), sonra R (döndür)

fig, axes = plt.subplots(1, 3, figsize=(16, 5.5))
plot_grid_transform(axes[0], S, "1) Önce Ölçekle (S)")
plot_grid_transform(axes[1], R, "2) Sonra Döndür (R)")
plot_grid_transform(axes[2], combined, "Birleşik Dönüşüm\n(R @ S)")
plt.tight_layout()
plt.show()

print("S matrisi:\n", S)
print("\nR matrisi:\n", R)
print("\nR @ S (birleşik):\n", combined)

"""**Gözlem:** Son panel, ilk iki dönüşümün **art arda uygulanmasıyla tam olarak aynı sonucu**
veriyor — çünkü `R @ S` matrisi bu bileşimi tek bir matriste kodluyor. `sklearn` pipeline'larındaki
`Pipeline([('scale', StandardScaler()), ('pca', PCA())])` mantığı da matematiksel olarak budur.
"""

# Ters Matris ve Lineer Sistemler: Normal Denklem ile Regresyon

#  Ax = b denklemini çözmek, "hangi vektör x, A dönüşümü altında b'ye gider?" sorusunu sormaktır. Eğer A tersinirse, tek çözüm x = A⁻¹b'dir.

# Veri biliminde lineer regresyonun kapalı-form çözümü olan normal denklem bu fikri kullanır.

# sklearn'ün LinearRegression'ı arka planda bunu yapar. California Housing verisiyle, "medyan gelir" özelliğinden "ev fiyatını" tahmin edelim.

from sklearn.linear_model import LinearRegression

# Basitlik için tek özellik: MedInc (medyan gelir)
x = X_house[:, house_feature_names.index('MedInc')]
y = y_house

# Tasarım matrisi X = [1, x] (bias terimi için 1'ler sütunu ekliyoruz)
X_design = np.column_stack([np.ones_like(x), x])

# --- NORMAL DENKLEM: elle lineer cebirle çözüm ---
beta_manual = np.linalg.inv(X_design.T @ X_design) @ X_design.T @ y
print("Elle (Normal Denklem) hesaplanan katsayılar [bias, eğim]:", beta_manual)

# --- sklearn ile doğrulama ---
model = LinearRegression()
model.fit(x.reshape(-1,1), y)
print("sklearn'ün bulduğu katsayılar   [bias, eğim]:", [model.intercept_, model.coef_[0]])

# Görselleştirme
fig, ax = plt.subplots(figsize=(8,6))
idx = np.random.RandomState(42).choice(len(x), 1500, replace=False)  # okunabilirlik için örnekleme
ax.scatter(x[idx], y[idx], alpha=0.25, s=15, color='#3498db', label='veri (örneklem)')
x_line = np.linspace(x.min(), x.max(), 100)
y_line = beta_manual[0] + beta_manual[1]*x_line
ax.plot(x_line, y_line, color='#e74c3c', lw=3,
        label=f'y = {beta_manual[0]:.2f} + {beta_manual[1]:.2f}·x\n(X^T X)^-1 X^T y ile bulundu')
ax.set_xlabel('Medyan Gelir (MedInc)')
ax.set_ylabel('Ev Fiyatı (100k $)')
ax.set_title('Normal Denklem: (XᵀX)⁻¹Xᵀy — Lineer Cebirle Regresyon')
ax.legend()
plt.tight_layout()
plt.show()

"""Gözlem: Elle lineer cebir ile bulduğumuz katsayılar, sklearn'ün optimizasyonla bulduğu katsayılarla birebir aynı çıkıyor. Bu, LinearRegression.fit() çağrısının arkasında aslında saf lineer cebir (matris tersi alma) olduğunu kanıtlıyor."""

# 7 - Matriste Rank Kavramı

#  Rank, bir dönüşümün çıktısının kapladığı uzayın boyut sayısıdır. "Full rank" bir matris bilgi kaybetmez; "rank-deficient" bir matris bir veya daha fazla boyutu ezer.

